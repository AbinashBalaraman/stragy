/**
 * Local deterministic helpers. These are NOT AI. Every result built from them is labelled
 * method "local_heuristic" and never claims an external model was connected.
 */
import type { StrategyAST, Timeframe } from '../../shared/strategy/types';
import { STRATEGY_TEMPLATES } from '../../shared/strategy/templates';
import { detectPatternFromPrompt } from './patterns';
import { ALL_SYMBOLS } from '../data/symbols';
import { strictValidateStrategy, diffStrategies } from './validation';
import type { AIVariation } from './types';

export const LOCAL_LABEL = 'local_heuristic';

const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const wordRe = (w: string) => new RegExp(`(^|[^a-z0-9])${escapeRe(w.toLowerCase())}($|[^a-z0-9])`);

const ALIASES: [string[], string][] = [
  [['reliance'], 'RELIANCE'], [['tcs', 'tata consultancy'], 'TCS'], [['infy', 'infosys'], 'INFY'], [['hdfc'], 'HDFCBANK'], [['icici'], 'ICICIBANK'],
  [['tata motors', 'tatamotors'], 'TATAMOTORS'], [['sbi', 'sbin'], 'SBIN'], [['airtel', 'bharti'], 'BHARTIARTL'], [['itc'], 'ITC'],
  [['l&t', 'larson', 'larsen'], 'LT'],
];

/** Whole-word symbol lookup ("switch" no longer matches ITC). Returns null if nothing matches. */
export function resolveSymbolFromPrompt(prompt: string): number | null {
  const lower = String(prompt ?? '').toLowerCase();
  for (const s of ALL_SYMBOLS) {
    if (wordRe(s.ticker).test(lower) || (s.name.length > 3 && wordRe(s.name).test(lower))) return s.id;
  }
  for (const [names, ticker] of ALIASES) if (names.some((n) => wordRe(n).test(lower))) return ALL_SYMBOLS.find(symbol => symbol.ticker === ticker)?.id ?? null;
  return null;
}

const clone = <T,>(v: T): T => JSON.parse(JSON.stringify(v));

export interface LocalCreateResult {
  detectedPattern?: string;
  variations: AIVariation[];
  warnings: string[];
}

/** Pattern-library lookup + two explicit, derived risk variants. Nothing beyond the template is invented. */
export function localCreateFromPrompt(prompt: string, fallbackSymbolId: number): LocalCreateResult {
  const warnings: string[] = [];
  const pattern = detectPatternFromPrompt(prompt);
  if (!pattern) return { variations: [], warnings: ['No pattern in the local library matched the prompt. Local matching only recognises known pattern names and keywords.'] };
  const symbolId = resolveSymbolFromPrompt(prompt) ?? fallbackSymbolId;
  const template = STRATEGY_TEMPLATES.find((t) => t.id === pattern.templateId) ?? null;
  if (!template) return { detectedPattern: pattern.name, variations: [], warnings: [`Pattern "${pattern.name}" has no template.`] };
  const base = template.strategy;

  const balanced = clone(base) as StrategyAST;
  balanced.name = `${pattern.name} (Balanced)`;
  balanced.universe = { symbolId, timeframe: base.universe.timeframe };

  const tight = clone(base) as StrategyAST;
  tight.name = `${pattern.name} (Tighter stop, wider target)`;
  tight.universe = { symbolId, timeframe: base.universe.timeframe };
  tight.risk.stopLoss = { ...base.risk.stopLoss, value: round(Math.max(0.5, base.risk.stopLoss.value * 0.7)) };
  if (base.risk.takeProfit) tight.risk.takeProfit = { ...base.risk.takeProfit, value: round(base.risk.takeProfit.value * 1.2) };

  const variations: AIVariation[] = [];
  const mk = (id: string, label: string, s: StrategyAST, summary: string, pros: string, cons: string) => {
    const v = strictValidateStrategy({ ...s, id: s.id ?? `local_${pattern.key}_${id}` });
    if (!v.success) { warnings.push(`Template variant "${label}" was dropped because it is not valid under strict validation: ${v.errors!.slice(0, 3).join('; ')}`); return; }
    variations.push({ id, name: `${pattern.name} - ${label}`, category: pattern.family, summary, pros, cons, strategy: v.data! });
  };
  mk('v1', 'Template as written', balanced, pattern.summary, 'Unmodified library template.', 'Library templates are illustrative, not tuned to your data.');
  mk('v2', 'Tighter stop, wider target', tight, 'Stop loss scaled by 0.7 and take profit by 1.2 relative to the template.', 'Smaller loss per stopped trade.', 'Tighter stops are hit more often; results are untested until you run a backtest.');
  warnings.push('Generated by local pattern lookup, not by an AI model. Review before applying.');
  return { detectedPattern: pattern.name, variations, warnings };
}

const round = (n: number) => Math.round(n * 100) / 100;

export interface LocalEditResult {
  strategy: StrategyAST;
  changes: string[];
  recognised: boolean;
  warnings: string[];
  errors?: string[];
}

const TF_MAP: [RegExp, Timeframe][] = [
  [/(^|[^a-z0-9])1\s?m(in)?($|[^a-z0-9])/i, '1m'], [/(^|[^a-z0-9])5\s?m(in)?($|[^a-z0-9])/i, '5m'],
  [/(^|[^a-z0-9])15\s?m(in)?($|[^a-z0-9])/i, '15m'], [/(^|[^a-z0-9])(1\s?h(our)?|hourly)($|[^a-z0-9])/i, '1H'],
  [/(^|[^a-z0-9])(1\s?d(ay)?|daily)($|[^a-z0-9])/i, '1D'], [/(^|[^a-z0-9])(1\s?w(eek)?|weekly)($|[^a-z0-9])/i, '1W'],
];

/** Applies only edits the user stated explicitly (stop/target/trailing values, timeframe, symbol, trade type). */
export function localEditStrategy(current: StrategyAST, instruction: string): LocalEditResult {
  const text = String(instruction ?? '');
  const lower = text.toLowerCase();
  const next = clone(current) as StrategyAST;
  const warnings: string[] = [];

  const num = (re: RegExp) => {
    const m = re.exec(lower);
    if (!m) return null;
    const value = Number(m[1]);
    if (!Number.isFinite(value) || value <= 0) return null;
    return { value, unit: (m[2] ?? '').toLowerCase() };
  };
  const unitToType = (unit: string, existing?: string): any => {
    if (unit === 'points' || unit === 'pts' || unit === 'point') return 'points';
    if (unit === '%' || unit === 'percent') return 'percent';
    if (unit === 'atr') return 'atr';
    return existing ?? 'percent';
  };
  const valueRe = (label: string) => new RegExp(`(?:^|[^a-z])(?:${label})(?:\\s|to|at|by|of|=|:|-)*?(\\d+(?:\\.\\d+)?)\\s*(%|percent|points?|pts|atr)?`);

  const sl = num(valueRe('stop[\\s-]*loss|stoploss|sl'));
  if (sl) next.risk.stopLoss = { type: unitToType(sl.unit, current.risk.stopLoss.type), value: sl.value };
  const tp = num(valueRe('take[\\s-]*profit|target|tp'));
  if (tp) next.risk.takeProfit = { type: unitToType(tp.unit === 'atr' ? '' : tp.unit, current.risk.takeProfit?.type), value: tp.value } as any;
  const tr = num(valueRe('trailing(?:[\\s-]*stop)?'));
  if (tr) next.risk.trailingStop = { ...(current.risk.trailingStop ?? {}), type: unitToType(tr.unit, current.risk.trailingStop?.type), value: tr.value } as any;

  if (/\b(timeframe|time frame|switch|change|use|on)\b/.test(lower) || tr === null) {
    for (const [re, tf] of TF_MAP) if (re.test(lower) && /\b(timeframe|time frame|switch|change|use|candles?|bars?)\b/.test(lower)) { next.universe.timeframe = tf; break; }
  }
  const symbolId = /\b(switch|change|use|test|run|backtest)\b/.test(lower) ? resolveSymbolFromPrompt(text) : null;
  if (symbolId && symbolId !== current.universe.symbolId) next.universe = { symbolId, instrumentId: 'legacy:' + symbolId, timeframe: next.universe.timeframe };
  if (/\bintraday\b/.test(lower) && /\b(switch|change|use|set)\b/.test(lower)) next.costs.tradeType = 'INTRADAY';
  if (/\bdelivery\b/.test(lower) && /\b(switch|change|use|set)\b/.test(lower)) next.costs.tradeType = 'DELIVERY';

  const changes = diffStrategies(current, next);
  if (!changes.length) return { strategy: current, changes: [], recognised: false, warnings: ['No explicit edit was recognised. Local editing only understands stop loss, take profit, trailing stop, timeframe, symbol, and intraday/delivery.'] };
  const valid = strictValidateStrategy(next);
  if (!valid.success) return { strategy: current, changes: [], recognised: false, warnings: ['The requested edit produced an invalid strategy and was rejected.'], errors: valid.errors };
  return { strategy: valid.data!, changes, recognised: true, warnings };
}
